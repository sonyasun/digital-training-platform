function showToast(message: string) {
  const existing = document.querySelector('.toast-notification')
  if (existing) existing.remove()

  const toast = document.createElement('div')
  toast.className = 'toast-notification'
  toast.textContent = message
  document.body.appendChild(toast)

  requestAnimationFrame(() => toast.classList.add('show'))
  setTimeout(() => {
    toast.classList.remove('show')
    setTimeout(() => { if (toast.parentNode) toast.parentNode.removeChild(toast) }, 300)
  }, 2000)
}

// ==========================================================================
// Lifecycle
// ==========================================================================
function initData() {
  const adapted = adaptNodesToChapters(props.pathNodes)
  adapted.forEach(ch => generateChapterPaths(ch))
  chapters.value = adapted

  // Determine initial chapter index
  let targetIdx = -1

  // 1. Try to use selectedChapter prop
  if (props.selectedChapter) {
    targetIdx = adapted.findIndex(ch => ch.chapterId === props.selectedChapter)
  }

  // 2. Fallback: find chapter containing currentNodeIndex node
  if (targetIdx < 0 && props.currentNodeIndex >= 0) {
    let nodeCounter = 0
    for (let ci = 0; ci < adapted.length; ci++) {
      const ch = adapted[ci]
      if (props.currentNodeIndex < nodeCounter + ch.nodes.length) {
        targetIdx = ci
        break
      }
      nodeCounter += ch.nodes.length
    }
  }

  // 3. Final fallback: first non-locked chapter
  if (targetIdx < 0) {
    targetIdx = adapted.findIndex(ch => ch.status !== 'locked')
    if (targetIdx < 0) targetIdx = 0
  }

  currentChapterIndex.value = targetIdx
}

