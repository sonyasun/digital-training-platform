function updateSvgTransform() {
  const svg = pathSvgRef.value
  if (!svg) return
  svg.style.transform = `translate(${zoomState.translateX}px, ${zoomState.translateY}px) scale(${zoomState.scale})`
  zoomLabel.value = `${Math.round(zoomState.scale * 100)}%`
}

function handleZoomIn() {
  zoomState.scale = Math.min(zoomState.maxScale, zoomState.scale + 0.25)
  updateSvgTransform()
}

function handleZoomOut() {
  zoomState.scale = Math.max(zoomState.minScale, zoomState.scale - 0.25)
  updateSvgTransform()
}

function handleResetView() {
  zoomState.scale = defaultZoomScale()
  zoomState.translateX = 0
  zoomState.translateY = 0
  updateSvgTransform()
}

function handleFitView() {
  zoomState.scale = defaultZoomScale()
  zoomState.translateX = 0
  zoomState.translateY = 0
  updateSvgTransform()
}

function initZoomPan() {
  const container = pathMapContainerRef.value
  const svg = pathSvgRef.value
  if (!container || !svg) return

  if (props.hideBirdView) {
    zoomState.scale = defaultZoomScale()
    zoomState.translateX = 0
    zoomState.translateY = 0
    updateSvgTransform()
    return
  }

  let startX = 0, startY = 0, startTranslateX = 0, startTranslateY = 0

  container.addEventListener('wheel', (e: WheelEvent) => {
    e.preventDefault()
    const delta = e.deltaY > 0 ? -0.15 : 0.15
    const oldScale = zoomState.scale
    zoomState.scale = Math.max(zoomState.minScale, Math.min(zoomState.maxScale, zoomState.scale + delta))
    const rect = container.getBoundingClientRect()
    const relX = e.clientX - rect.left
    const relY = e.clientY - rect.top
    const scaleChange = zoomState.scale / oldScale
    zoomState.translateX = relX - (relX - zoomState.translateX) * scaleChange
    zoomState.translateY = relY - (relY - zoomState.translateY) * scaleChange
    updateSvgTransform()
  }, { passive: false })

  container.addEventListener('mousedown', (e: MouseEvent) => {
    const target = e.target as HTMLElement
    if (target.closest('.node-group')) return
    zoomState.isDragging = true
    startX = e.clientX
    startY = e.clientY
    startTranslateX = zoomState.translateX
    startTranslateY = zoomState.translateY
    container.style.cursor = 'grabbing'
  })

  document.addEventListener('mousemove', (e: MouseEvent) => {
    if (!zoomState.isDragging) return
    const dx = e.clientX - startX
    const dy = e.clientY - startY
    zoomState.translateX = startTranslateX + dx
    zoomState.translateY = startTranslateY + dy
    updateSvgTransform()
  })

  document.addEventListener('mouseup', () => {
    if (zoomState.isDragging) {
      zoomState.isDragging = false
      container.style.cursor = 'grab'
    }
  })
}

