function initNodeHoverPopup() {
  const svg = pathSvgRef.value
  const canvasWrapper = canvasWrapperRef.value
  if (!svg || !canvasWrapper) return

  const nodeGroups = svg.querySelectorAll('.node-group')
  nodeGroups.forEach(group => {
    group.addEventListener('mouseenter', (e: Event) => {
      const g = group as SVGGElement
      const data = g.dataset
      const status = data.nodeStatus || 'locked'
      const nodeId = data.nodeId || ''

      popupData.title = data.nodeName || ''
      popupData.unit = data.nodeUnit || ''
      popupData.type = TYPE_MAP[data.nodeType || ''] || data.nodeType || ''
      popupData.progress = parseInt(data.nodeProgress || '0', 10)
      popupData.ppt = parseInt(data.ppt || '0', 10)
      popupData.video = parseInt(data.video || '0', 10)
      popupData.exercise = parseInt(data.exercise || '0', 10)
      popupData.statusColor = STATUS_COLOR_MAP[status] || '#94A3B8'

      popupVisible.value = true
      updatePopupPosition(e as MouseEvent)

      // Emit node-hover event
      const rawNode = props.pathNodes.find(n => n.id === nodeId)
      emit('node-hover', nodeId, rawNode || null)
    })

    group.addEventListener('mousemove', (e: Event) => {
      updatePopupPosition(e as MouseEvent)
    })

    group.addEventListener('mouseleave', () => {
      popupVisible.value = false
      emit('node-hover', null, null)
    })
  })
}

function updatePopupPosition(e: MouseEvent) {
  const wrapper = canvasWrapperRef.value
  if (!wrapper) return
  const wrapperRect = wrapper.getBoundingClientRect()
  const popupEl = document.getElementById('nodePopup')
  if (!popupEl) return

  const popupRect = popupEl.getBoundingClientRect()
  const offsetX = 20
  const offsetY = -10

  let left = e.clientX - wrapperRect.left + offsetX
  let top = e.clientY - wrapperRect.top + offsetY

  if (left + popupRect.width > wrapperRect.width - 10) {
    left = e.clientX - wrapperRect.left - popupRect.width - offsetX
  }
  if (top + popupRect.height > wrapperRect.height - 10) {
    top = wrapperRect.height - popupRect.height - 10
  }
  if (top < 10) top = 10

  popupData.left = left
  popupData.top = top
}

