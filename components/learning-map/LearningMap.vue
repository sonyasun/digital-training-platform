function switchChapter(targetIdx: number, animate = true) {
  if (targetIdx < 0 || targetIdx >= chapters.value.length) return
  currentChapterIndex.value = targetIdx

  const svg = pathSvgRef.value
  if (!svg) return

  const groups = svg.querySelectorAll('.chapter-group')
  groups.forEach((g, idx) => {
    const isActive = idx === targetIdx
    const state = isActive ? 'active-chapter' : (idx < targetIdx ? 'stowed-prev' : 'stowed-next')
    g.setAttribute('class', `chapter-group ${state}`)
    const transform = `translate(${ACTIVE_CHAPTER_X}, ${ACTIVE_CHAPTER_Y}) scale(1)`
    g.setAttribute('transform', transform)
  })

  if (!props.hideBirdView) renderExtensionLines()
  renderBirdViewList()

  // Reset zoom on chapter switch
  if (animate) {
    zoomState.scale = defaultZoomScale()
    zoomState.translateX = 0
    zoomState.translateY = 0
    updateSvgTransform()
  }

  // Emit chapter change
  const ch = chapters.value[targetIdx]
  if (ch) emit('chapter-change', ch.chapterId)
}

