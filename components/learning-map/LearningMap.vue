function adaptNodesToChapters(rawNodes: PathNodeLike[]): Chapter[] {
  if (!rawNodes || rawNodes.length === 0) return []

  // Group by chapterId
  const chapterMap = new Map<string, PathNodeLike[]>()
  for (const node of rawNodes) {
    if (!chapterMap.has(node.chapterId)) {
      chapterMap.set(node.chapterId, [])
    }
    chapterMap.get(node.chapterId)!.push(node)
  }

  const result: Chapter[] = []
  let chIdx = 0

  // Use currentNodeIndex to identify current node when status fields are missing
  const currentIdx = props.currentNodeIndex ?? -1
  const recommendedIds = new Set(props.recommendedNodeIds || [])
  const weakIds = new Set(props.weakNodeIds || [])

  for (const [chapterId, nodes] of chapterMap) {
    const chColor = CHAPTER_COLORS[chIdx % CHAPTER_COLORS.length]

    // Determine chapter status
    let chStatus = 'locked'
    for (let i = 0; i < nodes.length; i++) {
      const n = nodes[i]
      if (props.mode === 'teacher') {
        chStatus = 'mastered'
        break
      }
      // Check if this is the current learning node
      const isCurrentNode = i === currentIdx || n.isCurrent
      if (isCurrentNode || n.status === 'in-progress') {
        chStatus = 'active'
        break
      }
      if (chStatus !== 'active' && (n.status === 'completed' || (n.mastery !== undefined && n.mastery >= 80))) {
        chStatus = 'mastered'
      }
    }
    if (props.mode === 'teacher') chStatus = 'mastered'

    const baseChapterNodes: ChapterNode[] = nodes.map((n, i) => {
      let status = 'locked'
      let progress = 0

      if (props.mode === 'teacher') {
        status = 'mastered'
        progress = Math.round(n.mastery ?? 85)
      } else {
        const isCurrentNode = i === currentIdx || n.isCurrent
        const hasMastery = n.mastery !== undefined && n.mastery > 0

        // Determine status from multiple signals
        if (isCurrentNode) {
          status = 'active'
          progress = n.mastery ?? 50
        } else if (false && recommendedIds.has(n.id)) {
          status = 'active'
          progress = n.mastery ?? 60
        } else if (weakIds.has(n.id)) {
          status = 'weak'
          progress = n.mastery ?? 40
        } else if (n.status === 'in-progress') {
          status = 'active'
          progress = n.mastery ?? 50
        } else if (n.status === 'completed') {
          status = (n.mastery ?? 85) >= 80 ? 'mastered' : (n.mastery ?? 85) >= 60 ? 'attention' : 'weak'
          progress = n.mastery ?? 85
        } else if (hasMastery) {
          // Use mastery-based fallback
          if (n.mastery! >= 80) {
            status = 'mastered'
          } else if (n.mastery! >= 60) {
            status = 'attention'
          } else {
            status = 'weak'
          }
          progress = n.mastery!
        } else if (i < currentIdx) {
          // Nodes before current are likely completed
          status = 'mastered'
          progress = 80 + (i % 3) * 5
        } else {
          status = 'locked'
          progress = 0
        }
      }

      return {
        id: n.id,
        name: n.name,
        shortName: n.shortName,
        type: n.shapeType === 'practice' ? 'practice'
            : n.shapeType === 'integrated' ? 'integrated'
            : n.shapeType === 'reinforce' ? 'reinforce'
            : 'theory',
        status,
        progress,
        chapterId: n.chapterId,
        description: n.description,
        resources: n.resources,
        duration: n.duration
      }
    })

    const chapterNodes: ChapterNode[] = []
    baseChapterNodes.forEach((node, index) => {
      const source = nodes[index]
      const explicitBranch = source?.branch
      const useAutoBranch = chapterId !== 'ch2'
      const branch = explicitBranch
        ? {
            name: explicitBranch.name,
            status: explicitBranch.status || (
              node.status === 'mastered' || node.status === 'attention' || node.status === 'weak'
                ? 'mastered'
                : 'locked'
            ),
            progress: explicitBranch.progress ?? (
              node.status === 'mastered' || node.status === 'attention' || node.status === 'weak'
                ? Math.max(70, node.progress - 5)
                : 0
            ),
            side: explicitBranch.side || (index % 4 === 0 ? 'left' : 'right')
          }
        : useAutoBranch && props.mode === 'student' && node.status === 'mastered' && index % 2 === 0
          ? {
              name: `\u62d3\u5c55\u00b7${node.name.slice(0, 6)}`,
              status: 'mastered',
              progress: Math.max(70, node.progress - 5),
              side: index % 4 === 0 ? 'left' : 'right'
            }
          : undefined

      chapterNodes.push({ ...node, branch })

      if (props.mode === 'student' && node.status === 'weak' && node.type !== 'reinforce' && chapterId !== 'ch2') {
        chapterNodes.push({
          id: `${node.id}-reinforce`,
          name: '\u8865\u5f3a',
          type: 'reinforce',
          status: 'attention',
          progress: 0,
          chapterId: node.chapterId,
          description: '\u9488\u5bf9\u5f85\u8865\u5f3a\u77e5\u8bc6\u70b9\u7684\u4e13\u9879\u4efb\u52a1',
          resources: 'PPT 1 | \u89c6\u9891 2 | \u7ec3\u4e60 1',
          duration: '15\u5206\u949f'
        })
      }
    })

    const chapterMeta = props.chapterList.find(ch => ch.id === chapterId)
    result.push({
      id: chIdx,
      chapterId,
      name: `章节 ${chIdx + 1}`,
      color: chColor.color,
      colorLight: chColor.light,
      status: chStatus,
      nodes: chapterNodes,
      _points: [],
      _pathData: '',
      _segmentPaths: []
    })
    chIdx++
    result[result.length - 1]!.name = chapterMeta?.name || props.chapterName
  }

  return result
}

function generateChapterPaths(ch: Chapter) {
  const n = ch.nodes.length
  if (n < 1) return

  if (ch.chapterId === 'ch2') {
    generateSCurvePath(ch)
    return
  }

  const startX = 80
  const startY = 720
  const endX = 1120
  const endY = 80
  const points: { x: number; y: number }[] = []

  for (let i = 0; i < n; i++) {
    const t = n === 1 ? 0 : i / (n - 1)
    const baseX = startX + (endX - startX) * t
    const baseY = startY + (endY - startY) * t
    const wave = Math.sin(t * Math.PI * 2.5 + ch.id * 1.2) * 80
    const wave2 = Math.cos(t * Math.PI * 3 + ch.id * 0.8) * 50
    const x = Math.max(40, Math.min(1160, baseX + wave))
    const y = Math.max(50, Math.min(760, baseY + wave2 * (0.5 + t * 0.5)))
    points.push({ x, y })
  }

  ch._points = points
  ch._pathData = buildSmoothPath(points)

  const segments = splitIntoSegments(points, 4, 5)
  ch._segmentPaths = segments.map((seg, segIdx) => buildBlobPath(seg, ch.id, segIdx))
}

/** 第二岛：沿左下至右上的基准线作宽缓 S 弯，并按弧长均匀落点 */
function generateSCurvePath(ch: Chapter) {
  const n = ch.nodes.length
  const samples = 240
  const raw: { x: number; y: number }[] = []

  for (let i = 0; i < samples; i++) {
    const t = i / (samples - 1)
    const displacement = Math.sin(2 * Math.PI * t)
    raw.push({
      x: 150 + 1180 * t + 105 * displacement,
      y: 760 - 620 * t + 190 * displacement
    })
  }

  const dist = [0]
  for (let i = 1; i < samples; i++) {
    const dx = raw[i].x - raw[i - 1].x
    const dy = raw[i].y - raw[i - 1].y
    dist.push(dist[i - 1] + Math.hypot(dx, dy))
  }
  const total = dist[samples - 1] || 1

  const points: { x: number; y: number }[] = []
  for (let k = 0; k < n; k++) {
    const target = n === 1 ? 0 : (k / (n - 1)) * total
    let idx = dist.findIndex((d) => d >= target)
    if (idx < 0) idx = samples - 1
    if (idx === 0) {
      points.push({ ...raw[0] })
      continue
    }
    const d0 = dist[idx - 1]
    const d1 = dist[idx]
    const u = d1 === d0 ? 0 : (target - d0) / (d1 - d0)
    points.push({
      x: raw[idx - 1].x + (raw[idx].x - raw[idx - 1].x) * u,
      y: raw[idx - 1].y + (raw[idx].y - raw[idx - 1].y) * u
    })
  }

  ch._points = points
  ch._pathData = buildSmoothPath(points)
  const segments = splitIntoSegments(points, 4, 5)
  ch._segmentPaths = segments.map((seg, segIdx) => buildBlobPath(seg, ch.id, segIdx))
}

function buildSmoothPath(points: { x: number; y: number }[]): string {
  if (points.length < 2) return ''
  let d = `M ${points[0].x},${points[0].y}`
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[i - 1] || points[i]
    const p1 = points[i]
    const p2 = points[i + 1]
    const p3 = points[i + 2] || p2
    const cp1x = p1.x + (p2.x - p0.x) / 6
    const cp1y = p1.y + (p2.y - p0.y) / 6
    const cp2x = p2.x - (p3.x - p1.x) / 6
    const cp2y = p2.y - (p3.y - p1.y) / 6
    d += ` C ${cp1x},${cp1y} ${cp2x},${cp2y} ${p2.x},${p2.y}`
  }
  return d
}

function splitIntoSegments(points: { x: number; y: number }[], minSegs: number, maxSegs: number): { x: number; y: number }[][] {
  const n = points.length
  if (n < 2) return [points]
  let targetSegs = Math.max(minSegs, Math.min(maxSegs, Math.ceil(n / 3)))
  if (targetSegs < 2) targetSegs = 2
  if (targetSegs > n - 1) targetSegs = n - 1

  const segments: { x: number; y: number }[][] = []
  for (let s = 0; s < targetSegs; s++) {
    let startIdx = Math.round(s * (n - 1) / targetSegs)
    let endIdx = Math.round((s + 1) * (n - 1) / targetSegs)
    if (s === targetSegs - 1) endIdx = n - 1
    if (endIdx <= startIdx) endIdx = startIdx + 1
    if (startIdx < 0) startIdx = 0
    if (endIdx >= n) endIdx = n - 1

    const segPoints = points.slice(startIdx, endIdx + 1)
    if (startIdx > 0) {
      const prevP = points[startIdx - 1]
      const curP = points[startIdx]
      segPoints.unshift({ x: curP.x + (curP.x - prevP.x) * 0.4, y: curP.y + (curP.y - prevP.y) * 0.4 })
    } else {
      const nextP = points[1]
      const firstP = points[0]
      segPoints.unshift({ x: firstP.x + (firstP.x - nextP.x) * 0.4, y: firstP.y + (firstP.y - nextP.y) * 0.4 })
    }
    if (endIdx < n - 1) {
      const nextP2 = points[endIdx + 1]
      const endP = points[endIdx]
      segPoints.push({ x: endP.x + (endP.x - nextP2.x) * 0.4, y: endP.y + (endP.y - nextP2.y) * 0.4 })
    } else {
      const lastPrev = points[n - 2]
      const lastP = points[n - 1]
      segPoints.push({ x: lastP.x + (lastP.x - lastPrev.x) * 0.4, y: lastP.y + (lastP.y - lastPrev.y) * 0.4 })
    }
    segments.push(segPoints)
  }
  return segments
}

function buildBlobPath(points: { x: number; y: number }[], chIdx: number, segIdx: number): string {
  const n = points.length
  if (n < 2) return ''
  const segOffsetTop = 50 + Math.sin((chIdx * 2.3) + (segIdx || 0) * 1.5) * 12
  const segOffsetBot = 65 + Math.cos((chIdx * 1.7) + (segIdx || 0) * 1.1) * 14
  const offsetTop = segOffsetTop
  const offsetBot = segOffsetBot

  const topPoints: { x: number; y: number }[] = []
  const botPoints: { x: number; y: number }[] = []

  for (let i = 0; i < n; i++) {
    const p = points[i]
    const t = i / (n - 1)
    const normOffsetTop = offsetTop * (0.7 + 0.6 * Math.sin(t * Math.PI))
    const normOffsetBot = offsetBot * (0.7 + 0.6 * Math.sin(t * Math.PI))

    let dx: number, dy: number
    if (i === 0) { dx = points[1].x - points[0].x; dy = points[1].y - points[0].y }
    else if (i === n - 1) { dx = points[n - 1].x - points[n - 2].x; dy = points[n - 1].y - points[n - 2].y }
    else { dx = points[i + 1].x - points[i - 1].x; dy = points[i + 1].y - points[i - 1].y }

    const len = Math.sqrt(dx * dx + dy * dy) || 1
    const nx = -dy / len
    const ny = dx / len
    topPoints.push({ x: p.x + nx * normOffsetTop, y: p.y + ny * normOffsetTop })
    botPoints.push({ x: p.x - nx * normOffsetBot, y: p.y - ny * normOffsetBot })
  }

  const revBot = botPoints.slice().reverse()
  let d = `M ${topPoints[0].x},${topPoints[0].y}`
  for (let j = 0; j < topPoints.length - 1; j++) {
    const tp0 = topPoints[j - 1] || topPoints[j]
    const tp1 = topPoints[j]
    const tp2 = topPoints[j + 1]
    const tp3 = topPoints[j + 2] || tp2
    const c1x = tp1.x + (tp2.x - tp0.x) / 6
    const c1y = tp1.y + (tp2.y - tp0.y) / 6
    const c2x = tp2.x - (tp3.x - tp1.x) / 6
    const c2y = tp2.y - (tp3.y - tp1.y) / 6
    d += ` C ${c1x},${c1y} ${c2x},${c2y} ${tp2.x},${tp2.y}`
  }
  d += ` L ${revBot[0].x},${revBot[0].y}`
  for (let k = 0; k < revBot.length - 1; k++) {
    const bp0 = revBot[k - 1] || revBot[k]
    const bp1 = revBot[k]
    const bp2 = revBot[k + 1]
    const bp3 = revBot[k + 2] || bp2
    const bc1x = bp1.x + (bp2.x - bp0.x) / 6
    const bc1y = bp1.y + (bp2.y - bp0.y) / 6
    const bc2x = bp2.x - (bp3.x - bp1.x) / 6
    const bc2y = bp2.y - (bp3.y - bp1.y) / 6
    d += ` C ${bc1x},${bc1y} ${bc2x},${bc2y} ${bp2.x},${bp2.y}`
  }
  d += ' Z'
  return d
}

function buildStarPoints(cx: number, cy: number, outerR: number, innerR: number, points: number): string {
  const pts: string[] = []
  for (let i = 0; i < points * 2; i++) {
    const r = i % 2 === 0 ? outerR : innerR
    const angle = (i * Math.PI) / points - Math.PI / 2
    const x = cx + r * Math.cos(angle)
    const y = cy + r * Math.sin(angle)
    pts.push(x.toFixed(1) + ',' + y.toFixed(1))
  }
  return pts.join(' ')
}

