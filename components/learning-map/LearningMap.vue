function pathTangentAt(ch: Chapter, nIdx: number, pt: { x: number; y: number }) {
  const pts = ch._points
  const prev = pts[nIdx - 1] || pt
  const next = pts[nIdx + 1] || pt
  let tx = next.x - prev.x
  let ty = next.y - prev.y
  const len = Math.hypot(tx, ty) || 1
  tx /= len
  ty /= len
  return { tx, ty, nx: -ty, ny: tx }
}

