  detailData.status = info.text
  detailData.progress = parseInt(data.nodeProgress || '0', 10)
  detailData.progressText = `${detailData.progress}%`
  detailData.btn = info.btn
  detailData.disabled = status === 'locked'
  detailData.statusColor = info.color
  detailData.gradient = info.gradient

  if (props.mode === 'teacher') {
    detailData.status = ''
    detailData.progress = 0
    detailData.progressText = ''
    detailData.btn = '\u67e5\u770b\u8282\u70b9'
    detailData.disabled = false
  }

  detailOpen.value = true
  document.body.style.overflow = 'hidden'
}

function closeDetailPanel() {
  detailOpen.value = false
  document.body.style.overflow = ''
}

