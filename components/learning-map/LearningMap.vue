function createSvgNodeElement(node: ChapterNode, pt: { x: number; y: number }, ch: Chapter, displayStatus: string): SVGGElement {
  const g = document.createElementNS(SVG_NS, 'g')
  g.setAttribute('class', 'node-group')
  g.setAttribute('data-node-id', node.id)
  g.setAttribute('data-node-name', node.name)
  g.setAttribute('data-node-type', node.type)
  g.setAttribute('data-node-status', displayStatus)
  g.setAttribute('data-node-progress', String(node.progress))
  g.setAttribute('data-node-unit', ch.name)
  g.setAttribute('data-ppt', '1')
  g.setAttribute('data-video', '2')
  g.setAttribute('data-exercise', '1')

  const isDenseChapter = ch.chapterId === 'ch2'
  const nodeSize = isDenseChapter
    ? (displayStatus === 'active' ? 24 : node.type === 'reinforce' ? 21 : 19)
    : (displayStatus === 'active' ? 30 : 25)

  // Shadow
  const shadow = document.createElementNS(SVG_NS, 'ellipse')
  shadow.setAttribute('cx', String(pt.x))
  shadow.setAttribute('cy', String(pt.y + nodeSize + 4))
  shadow.setAttribute('rx', String(nodeSize - 2))
  shadow.setAttribute('ry', '5')
  shadow.setAttribute('fill', '#0F172A')
  shadow.setAttribute('opacity', displayStatus === 'locked' ? '0.08' : '0.15')
  shadow.setAttribute('filter', 'url(#softShadow)')
  g.appendChild(shadow)

  // Neon glow for active
  if (displayStatus === 'active') {
    const neon1 = document.createElementNS(SVG_NS, 'circle')
    neon1.setAttribute('class', 'neon-glow')
    neon1.setAttribute('cx', String(pt.x))
    neon1.setAttribute('cy', String(pt.y))
    neon1.setAttribute('r', String(nodeSize + 8))
    neon1.setAttribute('fill', '#34D399')
    neon1.setAttribute('opacity', '0.5')
    neon1.setAttribute('filter', 'url(#strongGlow)')
    g.appendChild(neon1)

    const neon2 = document.createElementNS(SVG_NS, 'circle')
    neon2.setAttribute('cx', String(pt.x))
    neon2.setAttribute('cy', String(pt.y))
    neon2.setAttribute('r', String(nodeSize + 2))
    neon2.setAttribute('fill', 'none')
    neon2.setAttribute('stroke', '#10B981')
    neon2.setAttribute('stroke-width', '1.5')
    neon2.setAttribute('stroke-dasharray', '5 4')
    neon2.setAttribute('class', 'dash-rotate')
    neon2.setAttribute('opacity', '0.5')
    g.appendChild(neon2)
  }

  // Node shape
  let nodeShape = 'circle'
  if (node.type === 'practice') nodeShape = 'diamond'
  else if (node.type === 'integrated') nodeShape = 'hexagon'
  else if (node.type === 'reinforce') nodeShape = 'star'

  // In teacher mode, always use the mastered (green) gradient.
  let gradRef = 'url(#gradMastered)'
  if (props.mode !== 'teacher') {
    gradRef = 'url(#gradLocked)'
    if (displayStatus === 'mastered') gradRef = 'url(#gradMastered)'
    else if (displayStatus === 'active') gradRef = 'url(#gradActive)'
    else if (displayStatus === 'attention') gradRef = 'url(#gradAttention)'
    else if (displayStatus === 'weak') gradRef = 'url(#gradWeak)'
  }

  let shapeEl: SVGElement
  if (nodeShape === 'circle') {
    shapeEl = document.createElementNS(SVG_NS, 'circle')
    shapeEl.setAttribute('cx', String(pt.x))
    shapeEl.setAttribute('cy', String(pt.y))
    shapeEl.setAttribute('r', String(nodeSize))
  } else if (nodeShape === 'diamond') {
    const half = nodeSize
    shapeEl = document.createElementNS(SVG_NS, 'polygon')
    const dPts = [
      [pt.x, pt.y - half],
      [pt.x + half, pt.y],
      [pt.x, pt.y + half],
      [pt.x - half, pt.y]
    ]
    shapeEl.setAttribute('points', dPts.map(p => `${p[0]},${p[1]}`).join(' '))
  } else if (nodeShape === 'star') {
    shapeEl = document.createElementNS(SVG_NS, 'polygon')
    shapeEl.setAttribute('points', buildStarPoints(pt.x, pt.y, nodeSize + 4, Math.max(10, nodeSize * 0.48), 5))
    shapeEl.setAttribute('class', 'reinforce-star')
  } else {
    // hexagon
    shapeEl = document.createElementNS(SVG_NS, 'polygon')
    const hPts: string[] = []
    for (let hi = 0; hi < 6; hi++) {
      const ha = (Math.PI / 3) * hi - Math.PI / 2
      hPts.push(`${(pt.x + nodeSize * Math.cos(ha)).toFixed(2)},${(pt.y + nodeSize * Math.sin(ha)).toFixed(2)}`)
    }
    shapeEl.setAttribute('points', hPts.join(' '))
  }

  shapeEl.setAttribute('class', 'lp-node')
  shapeEl.setAttribute('fill', gradRef)
  if (displayStatus !== 'locked') {
    shapeEl.setAttribute('filter', 'url(#nodeGlow)')
  }
  const glassStroke = displayStatus === 'locked' ? 'rgba(255,255,255,0.15)' : 'rgba(255,255,255,0.45)'
  shapeEl.setAttribute('stroke', glassStroke)
  shapeEl.setAttribute('stroke-width', nodeShape === 'circle' ? '1.2' : '1.6')
  g.appendChild(shapeEl)

  // Specular highlight
  if (nodeShape === 'circle') {
    const highlight = document.createElementNS(SVG_NS, 'ellipse')
    highlight.setAttribute('cx', String(pt.x - nodeSize * 0.35))
    highlight.setAttribute('cy', String(pt.y - nodeSize * 0.4))
    highlight.setAttribute('rx', String(nodeSize * 0.4))
    highlight.setAttribute('ry', String(nodeSize * 0.28))
    highlight.setAttribute('fill', '#FFFFFF')
    highlight.setAttribute('opacity', displayStatus === 'locked' ? '0.25' : '0.4')
    highlight.setAttribute('filter', 'url(#specularBlur)')
    g.appendChild(highlight)
  } else {
    const innerSize = nodeSize * 0.4
    const inner = document.createElementNS(SVG_NS, 'polygon')
    const innerPts: string[] = []
    if (nodeShape === 'diamond') {
      const dPts = [
        [pt.x, pt.y - innerSize],
        [pt.x + innerSize, pt.y],
        [pt.x, pt.y + innerSize],
        [pt.x - innerSize, pt.y]
      ]
      for (const p of dPts) innerPts.push(`${p[0].toFixed(2)},${p[1].toFixed(2)}`)
    } else {
      for (let ii = 0; ii < 6; ii++) {
        const ia = (Math.PI / 3) * ii - Math.PI / 2
        innerPts.push(`${(pt.x + innerSize * Math.cos(ia)).toFixed(2)},${(pt.y + innerSize * Math.sin(ia)).toFixed(2)}`)
      }
    }
    inner.setAttribute('points', innerPts.join(' '))
    inner.setAttribute('fill', '#FFFFFF')
    inner.setAttribute('opacity', '0.25')
    inner.setAttribute('transform', `translate(${-nodeSize * 0.25},${-nodeSize * 0.3})`)
    g.appendChild(inner)
  }

  // Progress text — hidden in teacher mode (no completion scores on map)
  if (displayStatus !== 'locked' && node.progress > 0 && props.mode !== 'teacher') {
    const text = document.createElementNS(SVG_NS, 'text')
    text.setAttribute('x', String(pt.x))
    text.setAttribute('y', String(pt.y + 4))
    text.setAttribute('text-anchor', 'middle')
    text.setAttribute('font-size', isDenseChapter ? (displayStatus === 'active' ? '10' : '9') : (displayStatus === 'active' ? '12' : '11'))
    text.setAttribute('font-weight', '700')
    text.setAttribute('fill', '#FFFFFF')
    text.textContent = `${node.progress}%`
    g.appendChild(text)
  }

  // Lock icon for locked status
  if (displayStatus === 'locked' && props.mode !== 'teacher') {
    const lockG = document.createElementNS(SVG_NS, 'g')
    lockG.setAttribute('transform', `translate(${pt.x - 6}, ${pt.y - 6})`)
    const lockArc = document.createElementNS(SVG_NS, 'path')
    lockArc.setAttribute('d', 'M -4 -2 L -4 -5 Q -4 -10 0 -10 Q 4 -10 4 -5 L 4 -2')
    lockArc.setAttribute('fill', 'none')
    lockArc.setAttribute('stroke', '#FFFFFF')
    lockArc.setAttribute('stroke-width', '1.5')
    lockArc.setAttribute('stroke-linecap', 'round')
    lockG.appendChild(lockArc)
    const lockBody = document.createElementNS(SVG_NS, 'rect')
    lockBody.setAttribute('x', '-6'); lockBody.setAttribute('y', '-2')
    lockBody.setAttribute('width', '12'); lockBody.setAttribute('height', '9'); lockBody.setAttribute('rx', '2')
    lockBody.setAttribute('fill', '#FFFFFF')
    lockG.appendChild(lockBody)
    const lockHole = document.createElementNS(SVG_NS, 'circle')
    lockHole.setAttribute('cx', '0'); lockHole.setAttribute('cy', '2.5'); lockHole.setAttribute('r', '1.2')
    lockHole.setAttribute('fill', '#94A3B8')
    lockG.appendChild(lockHole)
    g.appendChild(lockG)
  }

  return g
}

